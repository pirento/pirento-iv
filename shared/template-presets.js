export function presetFormatsFor(organization, timestamp = new Date().toISOString()) {
  return TEMPLATE_PRESETS.map((preset, index) => ({
    ...defaultFormatFor(organization),
    ...preset.settings,
    id: index === 0 ? `${organization.id}-standard` : `${organization.id}-preset-${preset.key}`,
    organizationId: organization.id,
    name: preset.name,
    description: preset.description,
    presetKey: preset.key,
    isDefault: index === 0,
    createdAt: timestamp,
    updatedAt: timestamp,
  }));
}
